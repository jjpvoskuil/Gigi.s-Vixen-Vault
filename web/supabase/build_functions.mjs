// Builds each Edge Function into ONE self-contained index.ts (what you paste into Supabase → Edge Functions).
//   node supabase/build_functions.mjs        (run from web/; npm test checks the output is up to date)
import { readFileSync, writeFileSync } from "node:fs";

const strip = (src) => src.replace(/^import .*$/gm, "").replace(/^export (const|function|class|async function)/gm, "$1");

export function buildVaultAi() {
  const ai = strip(readFileSync(new URL("../src/lib/ai.js", import.meta.url), "utf8"));
  const handler = strip(readFileSync(new URL("./functions/vault-ai/handler.js", import.meta.url), "utf8"));
  return `// GENERATED by web/supabase/build_functions.mjs — do not edit here; edit src/lib/ai.js or functions/vault-ai/handler.js.
// Supabase Edge Function "vault-ai". Paste this whole file into the dashboard editor and deploy.
import { createClient } from "npm:@supabase/supabase-js@2";

// ---------------------------------------------------------------- src/lib/ai.js
${ai}
// ---------------------------------------------------------------- functions/vault-ai/handler.js
${handler}
const ai = { isUntagged, tagRequest, cleanTag, mergeDescribe, outfitRequest, readOutfits, toolAnswer };
Deno.serve(makeHandler({ createClient, fetchFn: fetch, env: (k) => Deno.env.get(k), ai }));
`;
}

export function buildVaultPunch() {
  const punch = strip(readFileSync(new URL("../src/lib/punch.js", import.meta.url), "utf8"));
  const handler = strip(readFileSync(new URL("./functions/vault-punch/handler.js", import.meta.url), "utf8"));
  return `// GENERATED by web/supabase/build_functions.mjs — do not edit here; edit src/lib/punch.js or functions/vault-punch/handler.js.
// Supabase Edge Function "vault-punch". Paste this whole file into the dashboard editor and deploy.
import { createClient } from "npm:@supabase/supabase-js@2";

// ---------------------------------------------------------------- src/lib/punch.js
${punch}
// ---------------------------------------------------------------- functions/vault-punch/handler.js
${handler}
const punch = { newId, shotPath, newItem, applyEdit, applyStatus, textToB64, b64ToText, fileText };
Deno.serve(makePunchHandler({ createClient, fetchFn: fetch, env: (k) => Deno.env.get(k), punch }));
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("./functions/vault-ai/index.ts", import.meta.url), buildVaultAi());
  try { writeFileSync(new URL("./functions/vault-punch/index.ts", import.meta.url), buildVaultPunch()); } catch (e) { if (e.code !== "ENOENT") throw e; }
  console.log("built functions");
}
